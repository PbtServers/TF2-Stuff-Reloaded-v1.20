"""Migrate static cubes/poses from rafradek's historical projectile models without editing them."""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LEGACY = ROOT / 'src/main/java/rafradek/tf2weapons/client/model'
OUTPUT = ROOT / 'src/main/java/rafradek/tf2weapons/weaponclient/ProjectileGeometry.java'
MODELS = {'ROCKET': 'Rocket', 'GRENADE': 'Grenade', 'STICKY': 'Stickybomb', 'FLARE': 'Flare', 'SYRINGE': 'Syringe'}


def floats(arguments):
    return [value.strip().rstrip('fFdD') + 'F' for value in arguments.split(',')]


def generate():
    cases = []
    for kind, name in MODELS.items():
        source = (LEGACY / ('Model' + name + '.java')).read_text(encoding='utf-8')
        width = re.search(r'textureWidth\s*=\s*(\d+)', source)[1]
        height = re.search(r'textureHeight\s*=\s*(\d+)', source)[1]
        cubes = []
        for part, u, v in re.findall(r'(\w+)\s*=\s*new ModelRenderer\(this,\s*(\d+),\s*(\d+)\)', source):
            box = floats(re.search(re.escape(part) + r'\.addBox\(([^)]+)\)', source)[1])
            pose = floats(re.search(re.escape(part) + r'\.setRotationPoint\(([^)]+)\)', source)[1])
            rotation = re.search(r'setRotateAngle\(' + re.escape(part) + r',\s*([^)]+)\)', source)
            angles = floats(rotation[1]) if rotation else ['0F'] * 3
            mirror = '.mirror()' if re.search(re.escape(part) + r'\.mirror\s*=\s*true', source) else ''
            cubes.append(f'                root.addOrReplaceChild("{part}", CubeListBuilder.create().texOffs({u}, {v}){mirror}.addBox({", ".join(box[:6])}), PartPose.offsetAndRotation({", ".join(pose + angles)}));')
        cases.append(f'            case {kind} -> {{\n' + '\n'.join(cubes) + f'\n                return LayerDefinition.create(mesh, {width}, {height});\n            }}')
    OUTPUT.write_text('''package rafradek.tf2weapons.weaponclient;

import net.minecraft.client.model.geom.PartPose;
import net.minecraft.client.model.geom.builders.*;
import rafradek.tf2weapons.weapon.projectile.WeaponProjectile;

/** Static geometry migrated from rafradek's ModelRocket/Grenade/Stickybomb/Flare/Syringe (LGPL 2.1).
 * Generated by tools/generate_projectile_geometry.py; historical credits and sources retained.
 */
public final class ProjectileGeometry {
    public static LayerDefinition create(WeaponProjectile.Flight flight) {
        MeshDefinition mesh = new MeshDefinition();
        PartDefinition root = mesh.getRoot();
        switch (flight) {
''' + '\n'.join(cases) + '''
            case ARROW -> {
                root.addOrReplaceChild("shaft", CubeListBuilder.create().texOffs(0, 0).addBox(-6, -0.25F, -0.25F, 12, 0.5F, 0.5F), PartPose.ZERO);
                return LayerDefinition.create(mesh, 32, 32);
            }
            case ENERGY -> {
                root.addOrReplaceChild("beam", CubeListBuilder.create().texOffs(0, 0).addBox(-6, -0.5F, -0.5F, 12, 1, 1), PartPose.ZERO);
                return LayerDefinition.create(mesh, 16, 16);
            }
        }
        throw new IllegalArgumentException("Unknown projectile flight " + flight);
    }
}
''', encoding='utf-8')


if __name__ == '__main__':
    generate()
